import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'
import { fileURLToPath, URL } from 'node:url'

// ============================================================================
// Vite 构建配置文件
// 文档: https://vitejs.dev/config/
// ============================================================================

export default defineConfig({
  // --------------------------------------------------------------------------
  // 插件列表
  //   @vitejs/plugin-vue — 处理 .vue 单文件组件 (SFC)
  // --------------------------------------------------------------------------
  plugins: [vue()],

  // --------------------------------------------------------------------------
  // 路径别名 (resolve.alias)
  //   效果: import xxx from '@/api/ping' 等价于 import xxx from 'src/api/ping'
  //   好处: 不需要写 ../../ 相对路径，代码更清晰
  // --------------------------------------------------------------------------
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url))
    }
  },

  // --------------------------------------------------------------------------
  // 开发服务器配置 (仅 npm run dev 时生效)
  // --------------------------------------------------------------------------
  server: {
    // 监听端口（默认 5173）
    port: 5173,

    // 启动后自动在浏览器中打开
    open: true,

    // ------------------------------------------------------------------------
    // 开发环境 API 代理
    // 为什么需要代理?
    //   前端地址: http://localhost:5173
    //   后端地址: http://localhost:8080
    //   直接从前端发请求到 localhost:8080 会触发浏览器 CORS 跨域限制。
    //   虽然后端已配置 CORS 过滤器，但在开发阶段使用代理是更好的实践:
    //     - 避免 CORS 预检请求
    //     - 模拟生产环境同域部署
    //     - 方便调试（请求经过本地代理，可在浏览器 Network 中看到）
    //
    // 工作原理:
    //   前端调用 fetch('/api/ping')
    //   → Vite 开发服务器拦截 /api/* 请求
    //   → 转发到 http://localhost:8080/api/ping
    //   → 返回响应给前端
    //   对浏览器来说，请求是同源的 (http://localhost:5173/api/ping)
    // ------------------------------------------------------------------------
    proxy: {
      '/api': {
        // 后端目标地址
        target: 'http://localhost:8080',

        // changeOrigin: true
        //   修改请求头中的 Host 为目标地址的 Host
        //   避免后端因 Host 头不匹配而拒绝请求
        changeOrigin: true,

        // rewrite 可以重写路径（此处不需要，保留注释说明）
        // 例如: rewrite: (path) => path.replace(/^\/api/, '')
        // 会把 /api/ping → /ping
      }
    }
  }
})
